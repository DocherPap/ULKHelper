using ULKHelper.Logos;
using System.Text.Json;
var count=0;void Check(bool b,string n){if(!b)throw new Exception(n);count++;Console.WriteLine("PASS "+n);}
using var service=new LogosService();var catalog=service.Catalog;
Check(catalog.Actions.Length==56 && catalog.Actions.Select(a=>a.Number).SequenceEqual(Enumerable.Range(1,56)),"56个文理技能编号完整");
Check(catalog.Actions.Sum(a=>a.Recipes.Length)==115 && catalog.Shards.Length==9,"115配方与9类碎晶");
using var game=new Lumina.GameData("D:/Program Files (x86)/FFXIV/game/sqpack",new Lumina.LuminaOptions{DefaultExcelLanguage=Lumina.Data.Language.ChineseSimplified});
var actions=game.Excel.GetSheet<Lumina.Excel.Sheets.EurekaMagiaAction>()!.Where(a=>a.RowId>0).Select(a=>a.Action.RowId).ToHashSet();
Check(actions.SetEquals(catalog.Actions.Select(a=>a.Action)),"全部技能ID匹配本机游戏表");
var items=game.Excel.GetSheet<Lumina.Excel.Sheets.Item>()!;
Check(catalog.Shards.SelectMany(s=>s.Mnemes.Append(s.Item)).All(id=>items.GetRow(id).Name.ExtractText().Length>0),"碎晶及记忆物品ID有中文名称");
Check(catalog.Actions.SelectMany(a=>a.Recipes).SelectMany(r=>r).All(m=>catalog.Shards.Any(s=>s.Mnemes.Contains(m))),"所有配方原料均有鉴定来源");
using var json=JsonDocument.Parse("""{"results":[{"itemId":24007,"nq":{"minListing":{"world":{"price":100},"dc":{"price":60},"region":{"price":25}}}},{"itemId":24008,"nq":{"minListing":{"world":null,"dc":{"price":0},"region":{"price":40}}}}]}""");
var prices=LogosService.Parse(json.RootElement);
Check(prices[24007]==new LogosPrice(100,60,25),"Universalis解析本服大区国服三个范围");
Check(prices[24008].World==null&&prices[24008].Dc==null,"缺少或零报价保持未知");
Check(LogosService.Cost(catalog,prices,[24015,24015],0)==200,"配方重复材料累加采购基准");
Check(LogosService.Cost(catalog,prices,[24015],2)==25,"成本使用选定价格范围");
Check(LogosService.Cost(catalog,prices,[24810],0)==null,"缺少原料报价时成本未知");
var stone=catalog.Actions.Single(a=>a.Action==12991);
Check(stone.Recipes.Length==4 && stone.Recipes.Any(r=>r.SequenceEqual(new uint[]{24035})),"文理石肤四种组合完整，含直接记忆");
var allPrices=catalog.Shards.ToDictionary(s=>s.Item,_=>new LogosPrice(100,80,60));
Check(stone.Recipes.All(r=>LogosService.Cost(catalog,allPrices,r,0)!=null),"文理石肤四种配方在完整报价下均能估价");
Check(LogosService.Cost(catalog,prices,stone.Recipes[0],0)==null && service.MissingPrices(stone.Recipes[0],0).Contains(24013u),"石肤直接配方缺少24013碎晶报价时明确指出来源");
Check(LogosService.Cost(catalog,prices,new uint[]{24022,24022,24022},0)==null,"缺少对应范围报价不使用零价");
Check(LogosService.Cost(catalog,prices,new uint[]{24022,24022,24022},2)==120,"石肤可通过护盾三份在已知区域报价下计算替代组合");
